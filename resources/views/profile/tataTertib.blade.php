                <details name="tataTertib" class="py-3">
                    <summary class="text-base sm:text-base lg:text-base font-bold w-[100%] sm:w-[100%] lg:w-[100%]   text-gray-900 cursor-pointer font-nunito">Pasal 4 : Hak,Kewajiban dan larangan (Larangan)</summary>
                    <ol class="py-2">
                        <li class="text-justify text-sm sm:text-sm lg:text-sm mt-6 text-slate-600 leading-6">
                            Peserta didik dilarang melakukan pelanggaran kategori <b>Lisan</b> sebagai berikut:
                            <br>
                            1. Mengucapkan kata: kasar, cabul, dan atau kata lainnya yang tidak selaras dengan umur kalender. <br>
                            2. Memanggil teman dengan gelar-gelar negatif. <br>
                            3. Mencemooh, mengejek postur tubuh orang siapa pun, nama orang tua teman.
                        </li>
                        <li class="text-justify text-sm sm:text-sm lg:text-sm mt-6 text-slate-600 leading-6">
                            Peserta didik dilarang melakukan pelanggaran kategori <b>Tulisan</b> sebagai berikut:
                            <br>
                            1. Menulis nama diri sendiri, nama orang lain, dan atau kata apa pun di meja, kursi, dinding gedung, atau fasilitas sekolah lainnya kecuali di papan tulis kelas atau pengumuman. <br>
                            2. Menulis nama geng atau komunitas apa pun di lingkungan sekolah. <br>
                            3. Menulis status di media sosial tentang SMPN 16 Kota Cirebon.
                        </li>
                        <li class="text-justify text-sm sm:text-sm lg:text-sm mt-6 text-slate-600 leading-6">
                            Peserta didik dilarang melakukan pelanggaran kategori <b>Perbuatan</b> sebagai berikut:
                            <br>
                            1. Membawa dan atau mengonsumsi obat terlarang atau zat adiktif lainnya baik di dalam maupun di luar sekolah. <br>
                            2. Membawa, mengonsumsi, dan atau mengedarkan minuman keras atau zat/bahan lain yang bisa memabukkan baik di dalam maupun di luar sekolah. <br>
                            3. Berurusan dengan Aparat Penegak Hukum karena melakukan tindakan kriminal melawan hukum dan perundang-undangan yang berlaku. <br>
                            4. Mengubah atau memalsukan rapor. <br>
                            5. Memalsukan tanda tangan kepala sekolah/guru/orang tua/teman. <br>
                            6. Merusak sarana dan prasarana sekolah: memecahkan kaca, merusak kran air, merusak pintu/jendela/komputer, alat pengeras suara, dan sebagainya. <br>
                            7. Membuat, membawa, dan menunjukkan gambar, film, atau HP yang mengandung pornografi, pornokasi, dan SARA. <br>
                            8. Mengganggu/mengambil hak milik orang lain (mencuri). <br>
                            9. Menjadi anggota perkumpulan anak-anak nakal/geng yang meresahkan. <br>
                            10. Terlibat perkelahian/melawan guru, karyawan, teman, atau warga sekolah. <br>
                            11. Tidak mematuhi peraturan sekolah baik di dalam maupun di luar lingkungan sekolah.
                        </li>
                        <li class="text-justify text-sm sm:text-sm lg:text-sm mt-6 text-slate-600 leading-6">
                            Peserta didik dilarang melakukan pelanggaran kategori <b>Kedisiplinan</b> sebagai berikut:
                            <br>
                            1. Tidak mengikuti upacara, apel pagi, peringatan hari besar nasional/agama, atau acara resmi yang diadakan sekolah. <br>
                            2. Tidak masuk sekolah tanpa keterangan yang sah. <br>
                            3. Tidak mengerjakan tugas yang diberikan guru. <br>
                            4. Tidak mengikuti kegiatan ekstrakurikuler tanpa keterangan. <br>
                            5. Keluar kelas tanpa izin guru pengajar.
                        </li>
                        <li class="text-justify text-sm sm:text-sm lg:text-sm mt-6 text-slate-600 leading-6">
                            Peserta didik dilarang melakukan pelanggaran kategori <b>Ketertiban</b> sebagai berikut:
                            <br>
                            1. Tidak mengenakan seragam sesuai ketentuan. <br>
                            2. Memakai sepatu selain hitam polos. <br>
                            3. Memakai kaos kaki yang tidak sesuai dengan ketentuan. <br>
                            4. Memakai perhiasan emas berlebihan. <br>
                            5. Memakai aksesoris yang tidak wajar. <br>
                            6. Mengecat warna dasar rambut bagi peserta didik perempuan. <br>
                            7. Membawa sampah sembarangan/tidak pada tempatnya. <br>
                            8. Meletakkan sepeda tidak terikat atau tidak pada tempatnya.
                        </li>
                        <li class="text-justify text-sm sm:text-sm lg:text-sm mt-6 text-slate-600 leading-6">
                            Peserta didik dilarang melakukan pelanggaran kategori <b>Akhlak</b> sebagai berikut:
                            <br>
                            1. Berperilaku asusila terhadap lawan jenis maupun sejenis. <br>
                            2. Melakukan perundungan/bullying kepada teman baik langsung maupun melalui media sosial. <br>
                            3. Tidak hormat/mentaati peraturan/kegiatan agama sesuai dengan agama yang dianutnya.
                        </li>
                    </ol>

